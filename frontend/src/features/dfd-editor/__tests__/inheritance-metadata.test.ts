import { describe, expect, it } from 'vitest'
import { renderToStaticMarkup } from 'react-dom/server'
import { createElement } from 'react'
import { inheritanceMetadata } from '../components/threat-analysis/inheritance-metadata'
import { CountermeasureCard } from '../components/threat-analysis/CountermeasureCard'
import type { AnalysisCountermeasure } from '../types/threat-analysis'
import { transformAnalysisThreats, type AnalysisPayloadThreat } from '@/features/threat-models/api/threats'

describe('declared inheritance metadata', () => {
  it('handles API camel case and legacy snake case', () => {
    for (const cyclonedx of [
      { providingSystem: 'Platform', responsibilitySource: 'crm' },
      { providing_system: 'Platform', responsibility_source: 'crm' },
    ]) {
      expect(inheritanceMetadata({ cyclonedx })).toEqual({ providingSystem: 'Platform', responsibilitySource: 'crm' })
    }
  })

  it('ignores malformed metadata and preserves party fallback', () => {
    for (const metadata of [null, undefined, [], 'invalid', { cyclonedx: [] }, { cyclonedx: { providingSystem: {}, responsibilitySource: false } }]) {
      expect(inheritanceMetadata(metadata, 'Platform')).toEqual({ providingSystem: 'Platform', responsibilitySource: '' })
    }
  })

  it('renders escaped source text without promoting a gap status', () => {
    const countermeasure: AnalysisCountermeasure = {
      id: 'cm-1', countermeasureId: 'custom', threatId: 'threat-1', status: 'gap',
      createdAt: '', updatedAt: '', countermeasureName: 'Control',
      formatMetadata: { cyclonedx: { providingSystem: '<script>bad</script>', responsibilitySource: 'crm' } },
    }
    const html = renderToStaticMarkup(createElement(CountermeasureCard, {
      countermeasure, isOpen: false, onOpen: () => {},
    }))
    expect(html).toContain('Declared provider: &lt;script&gt;bad&lt;/script&gt;')
    expect(html).toContain('Source: crm')
    expect(html).toContain('data-countermeasure-status="gap"')
    expect(html).not.toContain('<script>')
  })

  it('preserves source metadata through the real analysis transformation', () => {
    const metadata = { cyclonedx: { providingSystem: 'Platform', responsibilitySource: 'crm' } }
    const threat: AnalysisPayloadThreat = {
      id: 1, number: 1, displayNumber: 'T1', wholeSystem: true,
      autoGenerated: false, libraryMismatch: false, targets: [],
      threatLibraryId: null, threatName: 'Synthetic threat', threatDescription: null,
      rating: null, status: 'exposed', triageStatus: 'open', decisionRationale: '',
      actorPersonaId: null, actorPersonaName: null, intent: '', accessLevel: '',
      countermeasures: [{
        id: 1, countermeasureLibraryId: null, countermeasureName: 'Synthetic control',
        countermeasureDescription: null, controlFunctions: null, controlNature: null,
        status: 'gap', priority: 'none', evidenceUrl: '', waiverReason: '',
        assignedOwnerEmail: null, verifiedByEmail: null, standardMappings: [],
        autoGenerated: false, number: 1, displayNumber: 'C1', targets: [],
        implementedBy: [], implementedByParty: '', source: '', formatMetadata: metadata,
      }],
    }
    const control = transformAnalysisThreats([threat])[0].countermeasures[0]
    expect(control.formatMetadata).toEqual(metadata)
    expect(control.status).toBe('gap')
    expect(inheritanceMetadata(control.formatMetadata)).toEqual({ providingSystem: 'Platform', responsibilitySource: 'crm' })
    delete threat.countermeasures[0].formatMetadata
    expect(transformAnalysisThreats([threat])[0].countermeasures[0].formatMetadata).toBeUndefined()
  })
})
